/* تقييم إجابة نصية */
function grade(ans, q){
  const t=(ans||'').toLowerCase().trim();
  if(t.length<12) return {s:0, why:'noAns'};
  let s=0;
  const hits=q.look.filter(k=>t.includes(k.toLowerCase())).length;
  s += Math.min(hits,3)/3*60;                       /* الصلة بالموضوع */
  if(t.length>=60) s+=15;                           /* التفصيل */
  if(t.length>=140) s+=10;
  if(/\d/.test(t)) s+= q.needNum?15:5;              /* الأرقام */
  if(q.needNum && !/\d/.test(t)) s-=25;
  return {s:Math.max(0,Math.min(100,Math.round(s))), hits};
}
/* قرار اللجنة من مجموع التقييم + أرقام حالة العمل */
function decide(scores, bc){
  let total=0, wsum=0;
  Q.forEach(q=>{ const v=scores[q.k]; if(v==null)return; total+=v*q.w; wsum+=q.w; });
  const answerScore = wsum? total/wsum : 0;
  /* تحليل مالي */
  const cost=parseFloat(bc.cost)||0, ben=parseFloat(bc.benefit)||0, yrs=parseFloat(bc.years)||0;
  const payback = (ben>0)? cost/ben : 99;
  const totalBen = ben*yrs;
  const roi = cost>0? ((totalBen-cost)/cost*100) : 0;
  let finScore=0;
  if(cost>0&&ben>0&&yrs>0){
    finScore += payback<=2?40 : payback<=3?30 : payback<=5?18 : 5;
    finScore += roi>=100?35 : roi>=50?26 : roi>=20?16 : roi>0?8 : 0;
    finScore += (yrs>=3&&yrs<=7)?25:12;
  }
  const overall = Math.round(answerScore*0.6 + finScore*0.4);
  const verdict = overall>=70?'approve' : overall>=50?'conditional' : 'reject';
  return {answerScore:Math.round(answerScore), finScore:Math.round(finScore),
    overall, verdict, payback:payback<99?payback.toFixed(1):null,
    roi:Math.round(roi), totalBen};
}
return {Q, grade, decide};
